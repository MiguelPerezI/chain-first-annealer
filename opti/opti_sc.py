"""
Optimized implementation of the algorithms in
  Ortiz, Lara, González, Borat,
  "A randomized greedy algorithm for piecewise linear motion planning",
  arXiv:2008.13290v2.

Every algorithm of Section 4 is implemented with the optimizations described
in optimized_algorithms.md.  Pure Python, no dependencies.
"""
from __future__ import annotations
import itertools, random, time
from collections import deque
from typing import Dict, FrozenSet, List, Optional, Sequence, Tuple

Vertex = int
VMap = Dict[Vertex, Vertex]          # simplicial (vertex) map, domain vertices -> codomain vertices
Facet = FrozenSet[Vertex]


# --------------------------------------------------------------------------- #
#  Target complex K with the pre-computed structures used by every algorithm   #
# --------------------------------------------------------------------------- #
class Complex:
    """Finite abstract simplicial complex given by its facets (maximal simplices)."""

    def __init__(self, facets: Sequence[Sequence[Vertex]]):
        self.facets: List[Facet] = [frozenset(f) for f in facets]
        self.vertices: List[Vertex] = sorted(set().union(*self.facets))
        self.vidx = {v: i for i, v in enumerate(self.vertices)}
        self.nfac = len(self.facets)
        self.all_facets_mask = (1 << self.nfac) - 1
        # facet -> bitmask over vertices
        self.fmask = [sum(1 << self.vidx[v] for v in f) for f in self.facets]
        # inverted index: vertex -> bitmask over facets containing it
        self.star = {v: 0 for v in self.vertices}
        for i, f in enumerate(self.facets):
            for v in f:
                self.star[v] |= 1 << i
        self._ext_cache: Dict[Facet, int] = {}
        # all-pairs graph distance on the 1-skeleton (one BFS per vertex)
        adj = {v: set() for v in self.vertices}
        for f in self.facets:
            for a in f:
                adj[a].update(f - {a})
        self.dist: Dict[Vertex, Dict[Vertex, int]] = {}
        for s in self.vertices:
            d = {s: 0}
            q = deque([s])
            while q:
                x = q.popleft()
                for y in adj[x]:
                    if y not in d:
                        d[y] = d[x] + 1
                        q.append(y)
            self.dist[s] = d

    # -- simplex membership: intersect the facet-bitsets of the vertices ------ #
    def is_simplex(self, S) -> bool:
        fm = self.all_facets_mask
        for v in S:
            fm &= self.star.get(v, 0)
            if not fm:
                return False
        return True

    # -- Ext(S) = { u : S ∪ {u} is a simplex }, as a bitmask over vertices ---- #
    def ext(self, S: Facet) -> int:
        r = self._ext_cache.get(S)
        if r is None:
            fm = self.all_facets_mask
            for v in S:
                fm &= self.star.get(v, 0)
            r = 0
            i = 0
            while fm:
                if fm & 1:
                    r |= self.fmask[i]
                fm >>= 1
                i += 1
            self._ext_cache[S] = r
        return r

    def mask_to_vertices(self, m: int) -> List[Vertex]:
        out = []
        i = 0
        while m:
            if m & 1:
                out.append(self.vertices[i])
            m >>= 1
            i += 1
        return out


# --------------------------------------------------------------------------- #
#  Domain (sub)complex J of L, generated by a set of facets of L               #
# --------------------------------------------------------------------------- #
class Domain:
    def __init__(self, facets: Sequence[Facet]):
        self.facets: List[Facet] = list(facets)
        self.vertices: List[Vertex] = sorted(set().union(*self.facets)) if self.facets else []
        self.star: Dict[Vertex, List[Facet]] = {v: [] for v in self.vertices}
        for f in self.facets:
            for v in f:
                self.star[v].append(f)

    def restrict(self, phi: VMap) -> VMap:
        return {v: phi[v] for v in self.vertices}


def image(phi: VMap, sigma: Facet) -> Facet:
    return frozenset(phi[v] for v in sigma)


# --------------------------------------------------------------------------- #
#  Contiguous  (Definition 2.3.1) — full and incremental versions              #
# --------------------------------------------------------------------------- #
def contiguous(phi: VMap, psi: VMap, dom: Domain, K: Complex) -> bool:
    """1-contiguity of two vertex maps on dom (also certifies both are simplicial)."""
    for s in dom.facets:
        if not K.is_simplex(image(phi, s) | image(psi, s)):
            return False
    return True


def contiguous_diff(phi: VMap, psi: VMap, dom: Domain, K: Complex) -> bool:
    """Same as `contiguous`, but only inspects facets touching a vertex where the
    maps differ (facets where they agree are simplices because phi is simplicial)."""
    diff = [v for v in dom.vertices if phi[v] != psi[v]]
    if not diff:
        return True
    # O(1) necessary condition: images of every vertex must be equal or adjacent
    for v in diff:
        if K.dist[phi[v]].get(psi[v], 99) > 1:
            return False
    seen = set()
    for v in diff:
        for s in dom.star[v]:
            if s in seen:
                continue
            seen.add(s)
            if not K.is_simplex(image(phi, s) | image(psi, s)):
                return False
    return True


def admissible_values(phi: VMap, w: Vertex, dom: Domain, K: Complex) -> int:
    """Bitmask of u ∈ V_K such that the map phi[w := u] is simplicial AND
    1-contiguous to phi.  Both conditions reduce to  phi(σ) ∪ {u} ∈ K  for the
    facets σ ∋ w  (the paper's list L_{phi,w}, computed with bitset ANDs)."""
    m = (1 << len(K.vertices)) - 1
    for s in dom.star[w]:
        m &= K.ext(image(phi, s))
        if not m:
            break
    return m & ~(1 << K.vidx[phi[w]])


# --------------------------------------------------------------------------- #
#  Algorithm 1: LocalSearch (optimized)                                       #
# --------------------------------------------------------------------------- #
def local_search(phi: VMap, target: VMap, dom: Domain, K: Complex,
                 M: int, r: float, rng: random.Random) -> List[VMap]:
    """Randomized greedy walk from phi to target in the space of simplicial maps
    dom -> K.  Returns a contiguity chain [phi, ..., target] or [] on failure.

    Optimizations w.r.t. Algorithm 1 of the paper:
      * candidate steps are enumerated exactly (no rejection sampling, no full
        Contiguous call per try);
      * the distance d(f, target) is updated in O(1);
      * termination as soon as the current map is 1-contiguous to target
        (maintained incrementally with a 'bad facet' counter);
      * the vertex to mutate is sampled with weight ∝ its defect;
      * steepest-descent step choice, tabu on immediate reversal.
    """
    if not dom.vertices:
        return [dict(phi), dict(target)]
    if contiguous(phi, target, dom, K):
        return [dict(phi), dict(target)]

    cur = dict(phi)
    chain = [dict(cur)]
    V = dom.vertices
    defect = {v: K.dist[cur[v]][target[v]] for v in V}
    bad = {s: not K.is_simplex(image(cur, s) | image(target, s)) for s in dom.facets}
    nbad = sum(bad.values())
    tabu: Optional[Tuple[Vertex, Vertex]] = None

    for _ in range(M):
        # ---- pick a vertex, biased toward vertices still far from the target
        weights = [defect[v] + 0.25 for v in V]
        w = rng.choices(V, weights)[0]
        adm = admissible_values(cur, w, dom, K)
        if not adm:
            continue
        cands = K.mask_to_vertices(adm)
        if tabu and tabu[0] == w and len(cands) > 1:
            cands = [u for u in cands if u != tabu[1]]
        tw = target[w]
        if rng.random() < r:                        # exploration step
            u = rng.choice(cands)
        else:                                       # greedy (steepest) step
            best = min(K.dist[u][tw] for u in cands)
            if best >= defect[w]:
                continue                            # no improving step at w
            u = rng.choice([c for c in cands if K.dist[c][tw] == best])
        # ---- take the step, update incremental state on star(w) only
        old = cur[w]
        cur[w] = u
        defect[w] = K.dist[u][tw]
        for s in dom.star[w]:
            nb = not K.is_simplex(image(cur, s) | image(target, s))
            if nb != bad[s]:
                nbad += 1 if nb else -1
                bad[s] = nb
        tabu = (w, old)
        chain.append(dict(cur))
        if nbad == 0:                               # cur ~1 target: done
            if cur != target:
                chain.append(dict(target))
            return chain
    return []


# --------------------------------------------------------------------------- #
#  Algorithm 2: Reduce (optimized)                                            #
# --------------------------------------------------------------------------- #
def reduce_chain(chain: List[VMap], dom: Domain, K: Complex) -> List[VMap]:
    """Greedy farthest-jump shortening of a contiguity chain, with an O(|diff|)
    pre-filter and facet checks restricted to the differing vertices.
    Run forward and backward; return the shorter result; iterate to fixpoint."""

    def one_pass(ch: List[VMap]) -> List[VMap]:
        c = len(ch) - 1
        out = [ch[0]]
        j = 0
        while j < c:
            i = c
            while i > j + 1 and not contiguous_diff(ch[j], ch[i], dom, K):
                i -= 1
            out.append(ch[i])
            j = i
        return out

    best = chain
    while True:
        fwd = one_pass(best)
        bwd = one_pass(best[::-1])[::-1]
        cand = fwd if len(fwd) <= len(bwd) else bwd
        if len(cand) >= len(best):
            return best
        best = cand


# --------------------------------------------------------------------------- #
#  A "part": a contiguity subcomplex together with its certificate chain      #
# --------------------------------------------------------------------------- #
class Part:
    """A contiguity subcomplex (set of facets of L) with its certificate chain.

    `failed` is a soft cache of facets whose addition failed: facet -> (chain
    version at failure, #failures).  By monotonicity (chains restrict to sub-
    complexes) a *true* failure stays a failure as the part grows, but a
    LocalSearch miss is only probabilistic evidence, so a facet is retried once
    after the chain has changed and dropped for good after two misses."""

    def __init__(self, facets: Sequence[Facet], chain: List[VMap]):
        self.facets: set = set(facets)
        self.chain: List[VMap] = chain          # chain[0] = psi|J, chain[-1] = psi'|J
        self.version = 0
        self.failed: Dict[Facet, Tuple[int, int]] = {}

    def set_chain(self, chain: List[VMap]) -> None:
        self.chain = chain
        self.version += 1

    def skip(self, sigma: Facet) -> bool:
        rec = self.failed.get(sigma)
        return rec is not None and (rec[1] >= 2 or rec[0] == self.version)

    def note_failure(self, sigma: Facet) -> None:
        rec = self.failed.get(sigma)
        self.failed[sigma] = (self.version, 1 if rec is None else rec[1] + 1)

    def domain(self) -> Domain:
        return Domain(sorted(self.facets, key=sorted))

    def __len__(self):
        return len(self.facets)


def chain_valid_on_facet(chain: List[VMap], sigma: Facet, K: Complex) -> bool:
    """Is the chain (already defined on the vertices of sigma) a contiguity chain
    on the facet sigma?  O(c) simplex tests, no LocalSearch."""
    prev = image(chain[0], sigma)
    if not K.is_simplex(prev):
        return False
    for m in chain[1:]:
        cur = image(m, sigma)
        if not K.is_simplex(prev | cur):
            return False
        prev = cur
    return True


def extend_chain_dp(chain: List[VMap], sigma: Facet, new_vs: List[Vertex],
                    psi: VMap, psi2: VMap, K: Complex, max_states: int = 4096) -> Optional[List[VMap]]:
    """Assign values on the new vertices of sigma along the whole chain by
    dynamic programming (states = tuples of K-vertices), so that every map is
    simplicial on sigma and consecutive maps are 1-contiguous on sigma.
    Returns the extended chain or None."""
    if len(K.vertices) ** len(new_vs) > max_states:
        return None
    old_vs = [v for v in sigma if v not in new_vs]
    states_all = list(itertools.product(K.vertices, repeat=len(new_vs)))
    start = tuple(psi[v] for v in new_vs)
    goal = tuple(psi2[v] for v in new_vs)

    def img(i, a):
        return frozenset(chain[i][v] for v in old_vs) | frozenset(a)

    c = len(chain) - 1
    # forward DP: feasible[i] = {state: predecessor}
    feas: List[Dict[tuple, Optional[tuple]]] = []
    if not K.is_simplex(img(0, start)):
        return None
    feas.append({start: None})
    for i in range(1, c + 1):
        layer = {}
        cand_states = [goal] if i == c else states_all
        for a in cand_states:
            Ia = img(i, a)
            if not K.is_simplex(Ia):
                continue
            for b in feas[i - 1]:
                if K.is_simplex(img(i - 1, b) | Ia):
                    layer[a] = b
                    break
        if not layer:
            return None
        feas.append(layer)
    if goal not in feas[c]:
        return None
    # reconstruct
    assign = [None] * (c + 1)
    a = goal
    for i in range(c, -1, -1):
        assign[i] = a
        a = feas[i][a]
    out = []
    for i, m in enumerate(chain):
        m2 = dict(m)
        for v, val in zip(new_vs, assign[i]):
            m2[v] = val
        out.append(m2)
    return out


# --------------------------------------------------------------------------- #
#  Algorithm 3: AddFacet (optimized) and the RCC / AddFacets iteration         #
# --------------------------------------------------------------------------- #
class Stats:
    def __init__(self):
        self.ls_calls = 0
        self.ls_iters_budget = 0
        self.free_adds = 0
        self.dp_adds = 0
        self.warm_adds = 0
        self.cold_adds = 0
        self.failures = 0


def try_add_facet(part: Part, sigma: Facet, psi: VMap, psi2: VMap, K: Complex,
                  M: int, r: float, rng: random.Random, st: Stats,
                  allow_ls: bool = True) -> bool:
    """Try to enlarge `part` by the facet sigma, cheapest certificate first:
       1. no new vertices & existing chain already valid on sigma   (O(c))
       2. new vertices: DP extension of the existing chain          (O(c·S²))
       3. warm-started LocalSearch between the longest valid prefix and suffix
       4. cold LocalSearch on the enlarged domain (the paper's AddFacet)
    On success the part (facets+chain) is updated in place."""
    if part.skip(sigma):
        return False
    dom_vs = set().union(*part.facets) if part.facets else set()
    new_vs = [v for v in sorted(sigma) if v not in dom_vs]
    chain = part.chain

    if not new_vs:
        if chain_valid_on_facet(chain, sigma, K):
            part.facets.add(sigma)
            st.free_adds += 1
            return True
    else:
        ext = extend_chain_dp(chain, sigma, new_vs, psi, psi2, K)
        if ext is not None:
            part.set_chain(ext)
            part.facets.add(sigma)
            st.dp_adds += 1
            return True

    if not allow_ls:
        return False

    new_dom = Domain(sorted(part.facets | {sigma}, key=sorted))
    p0, p1 = new_dom.restrict(psi), new_dom.restrict(psi2)

    if not new_vs:
        # ---- warm start: keep the longest valid prefix / suffix of the chain
        k = 0
        while k + 1 < len(chain) and K.is_simplex(image(chain[k], sigma) | image(chain[k + 1], sigma)):
            k += 1
        m = len(chain) - 1
        while m - 1 > k and K.is_simplex(image(chain[m - 1], sigma) | image(chain[m], sigma)):
            m -= 1
        st.ls_calls += 1
        st.ls_iters_budget += M
        mid = local_search(chain[k], chain[m], new_dom, K, M, r, rng)
        if mid:
            part.set_chain(reduce_chain(chain[:k] + mid + chain[m + 1:], new_dom, K))
            part.facets.add(sigma)
            st.warm_adds += 1
            return True

    # ---- cold start (the original AddFacet test)
    st.ls_calls += 1
    st.ls_iters_budget += M
    ch = local_search(p0, p1, new_dom, K, M, r, rng)
    if ch:
        part.set_chain(reduce_chain(ch, new_dom, K))
        part.facets.add(sigma)
        st.cold_adds += 1
        return True
    part.note_failure(sigma)        # monotonicity: J ∪ σ infeasible ⇒ J' ∪ σ infeasible for J' ⊇ J
    st.failures += 1
    return False


def add_facets(part: Part, candidates: Sequence[Facet], psi: VMap, psi2: VMap, K: Complex,
               M: int, r: float, rng: random.Random, st: Stats, explore: float = 0.3) -> Part:
    """AddFacets / RCC core: greedily grow `part` inside `candidates`.
    Candidate set is persistent (a facet is tried at most once per LocalSearch
    failure), adjacency-ordered, and every success is followed by a 'free sweep'
    adding all facets certified by the current chain without any search."""
    pending = set(candidates) - part.facets

    def free_sweep():
        added = True
        while added:
            added = False
            for s in list(pending):
                if try_add_facet(part, s, psi, psi2, K, M, r, rng, st, allow_ls=False):
                    pending.discard(s)
                    added = True

    free_sweep()
    while pending:
        dom_vs = set().union(*part.facets)
        if rng.random() < explore:
            sigma = rng.choice(sorted(pending, key=sorted))     # the paper's uniformly random facet
        else:
            # most-adjacent first (fewest new vertices, most shared vertices), random tie-break
            sigma = min(pending, key=lambda s: (len(s - dom_vs), -len(s & dom_vs), rng.random()))
        pending.discard(sigma)
        if try_add_facet(part, sigma, psi, psi2, K, M, r, rng, st):
            free_sweep()
    return part


def rcc(candidates: Sequence[Facet], psi: VMap, psi2: VMap, K: Complex,
        M: int, r: float, rng: random.Random, st: Stats, seed: Optional[Facet] = None) -> Part:
    """RandomContiguitysubComplex: start from a random facet (a contiguity
    subcomplex whenever K is connected) and grow it with add_facets."""
    cands = list(candidates)
    sigma = seed if seed is not None else rng.choice(cands)
    d = Domain([sigma])
    ch = local_search(d.restrict(psi), d.restrict(psi2), d, K, M, r, rng)
    st.ls_calls += 1
    if not ch:
        raise RuntimeError("single facet is not a contiguity subcomplex: K disconnected?")
    part = Part([sigma], reduce_chain(ch, d, K))
    return add_facets(part, cands, psi, psi2, K, M, r, rng, st)


# --------------------------------------------------------------------------- #
#  Algorithm 4: Covering (optimized)                                          #
# --------------------------------------------------------------------------- #
def covering(L_facets: Sequence[Facet], psi: VMap, psi2: VMap, K: Complex,
             M: int, r: float, rng: random.Random, st: Stats, restarts: int = 3) -> List[Part]:
    """Partition the facets of L into contiguity subcomplexes.  Greedy set
    cover: each round runs RCC `restarts` times on the uncovered facets and keeps
    the largest result; before opening a new part, uncovered facets are first
    offered to the existing parts (first-fit)."""
    A = set(L_facets)
    parts: List[Part] = []
    while A:
        # first-fit: try to attach leftover facets to existing parts (cheap certificates only)
        for p in parts:
            for s in list(A):
                if try_add_facet(p, s, psi, psi2, K, M, r, rng, st, allow_ls=False):
                    A.discard(s)
        if not A:
            break
        best = None
        for _ in range(restarts):
            cand = rcc(sorted(A, key=sorted), psi, psi2, K, M, r, rng, st)
            if best is None or len(cand) > len(best):
                best = cand
            if len(best) == len(A):
                break
        parts.append(best)
        A -= best.facets
    return parts


# --------------------------------------------------------------------------- #
#  Algorithm 5: OptimizedCovering (optimized)                                 #
# --------------------------------------------------------------------------- #
def potential(parts: List[Part]) -> Tuple[int, int]:
    """Lexicographic objective: fewer parts first, then more 'lopsided' sizes."""
    return (len(parts), -sum(len(p) ** 2 for p in parts))


def clone_parts(parts: List[Part]) -> List[Part]:
    out = []
    for p in parts:
        q = Part(p.facets, [dict(m) for m in p.chain])
        q.version = p.version
        q.failed = dict(p.failed)
        out.append(q)
    return out


def absorb_smallest(parts: List[Part], psi: VMap, psi2: VMap, K: Complex,
                    M: int, r: float, rng: random.Random, st: Stats) -> bool:
    """Direct greedy move: try to distribute every facet of the smallest part
    among the other parts (cheap certificates first, then search).  Returns True
    if the smallest part disappeared."""
    parts.sort(key=len, reverse=True)
    small = parts[-1]
    others = parts[:-1]
    if not others:
        return False
    work = clone_parts(others)
    left = set(small.facets)
    for allow_ls in (False, True):
        for s in sorted(left, key=sorted):
            for p in sorted(work, key=len, reverse=True):
                if try_add_facet(p, s, psi, psi2, K, M, r, rng, st, allow_ls=allow_ls):
                    left.discard(s)
                    break
        if not left:
            parts[:] = work
            return True
    return False


def optimized_covering(L_facets: Sequence[Facet], psi: VMap, psi2: VMap, K: Complex,
                       M: int = 1000, r: float = 0.1, N: int = 200, t: int = 1,
                       patience: int = 40, seed: int = 0, restarts: int = 3,
                       time_limit: float = float("inf"),
                       verbose: bool = False) -> Tuple[List[Part], Stats]:
    rng = random.Random(seed)
    st = Stats()
    t_start = time.perf_counter()
    parts = covering(L_facets, psi, psi2, K, M, r, rng, st, restarts=restarts)
    if verbose:
        print(f"  Covering: {len(parts)} parts, sizes {sorted((len(p) for p in parts), reverse=True)}")
    i = j = 0
    stale = 0
    while i < N and len(parts) > t and stale < patience and time.perf_counter() - t_start < time_limit:
        i += 1
        before = potential(parts)
        # -- move A: absorb the smallest part into the others
        if absorb_smallest(parts, psi, psi2, K, M, r, rng, st):
            if verbose:
                print(f"  it {i}: absorbed smallest part -> {len(parts)} parts")
            stale = 0
            continue
        # -- move B: the paper's step (2)+(3) with the improved acceptance test
        old = clone_parts(parts)
        parts.sort(key=len, reverse=True)
        p = len(parts) - 1
        j = min(j, p)
        D = set().union(*(q.facets for q in parts[j:]))
        JP = rcc(sorted(D, key=sorted), psi, psi2, K, M, r, rng, st)
        if len(JP) < len(parts[j]):
            JP = clone_parts([parts[j]])[0]
        D2 = D | (parts[j - 1].facets if j > 0 else set())
        JQ = add_facets(JP, sorted(D2 - JP.facets, key=sorted), psi, psi2, K, M, r, rng, st)
        if j > 0 and len(JQ) < len(parts[j - 1]):
            JQ = clone_parts([parts[j - 1]])[0]
        new_parts = [clone_parts([q])[0] for q in parts[:max(0, j - 1)]] + [JQ]
        for q in parts[max(0, j - 1):]:
            rest = q.facets - JQ.facets
            if rest:
                if rest == q.facets:
                    new_parts.append(clone_parts([q])[0])
                else:
                    # the part shrank: restrict its chain to the remaining vertices,
                    # re-reduce it, and drop the failure cache (monotonicity no longer applies)
                    nd = Domain(sorted(rest, key=sorted))
                    ch = reduce_chain([nd.restrict(m) for m in q.chain], nd, K)
                    new_parts.append(Part(rest, ch))
        if potential(new_parts) <= before:          # never accept a worse partition
            parts = new_parts
        else:
            parts = old
        after = potential(parts)
        stale = 0 if after < before else stale + 1
        if verbose and after < before:
            print(f"  it {i}: {len(parts)} parts, sizes {sorted((len(p) for p in parts), reverse=True)}")
        j = j + 1 if j + 1 <= len(parts) - 1 else 0
    for p in parts:
        p.chain = reduce_chain(p.chain, p.domain(), K)
    return parts, st


# --------------------------------------------------------------------------- #
#  Helpers: ordered simplicial product, projections, verification             #
# --------------------------------------------------------------------------- #
def ordered_product(K1: Complex, K2: Complex, label=lambda a, b: (a, b)) -> List[Facet]:
    """Facets of the ordered simplicial product: maximal chains (lattice paths) in σ×τ."""
    facets = set()
    for s in K1.facets:
        a = sorted(s)
        for t in K2.facets:
            b = sorted(t)
            p, q = len(a) - 1, len(b) - 1
            for moves in itertools.combinations(range(p + q), p):
                i = jj = 0
                chain = [label(a[0], b[0])]
                for step in range(p + q):
                    if step in moves:
                        i += 1
                    else:
                        jj += 1
                    chain.append(label(a[i], b[jj]))
                facets.add(frozenset(chain))
    return sorted(facets, key=sorted)


def verify_system(parts: List[Part], L_facets: Sequence[Facet], psi: VMap, psi2: VMap, K: Complex) -> None:
    """Independent check with the plain Definition 2.3: partition + valid chains."""
    covered = set()
    for p in parts:
        assert not (p.facets & covered), "parts overlap"
        covered |= p.facets
        d = p.domain()
        ch = p.chain
        assert ch[0] == d.restrict(psi) and ch[-1] == d.restrict(psi2), "chain endpoints"
        for a, b in zip(ch, ch[1:]):
            assert contiguous(a, b, d, K), "chain link not contiguous"
    assert covered == set(L_facets), "not a covering"


def run_tc(K: Complex, name: str, M: int, r: float, N: int, t: int, seed: int = 0, restarts: int = 3,
           patience: int = 40, time_limit: float = float("inf"), verbose=True):
    """Estimate SC_strict(K) = SD(pi1, pi2) on the ordered product K×K."""
    n = len(K.vertices)
    lab = lambda a, b: n * a + b           # vertex (a,b) of K×K labelled n*a+b (as in the paper)
    Lf = ordered_product(K, K, lab)
    verts = sorted(set().union(*Lf))
    pi1 = {v: v // n for v in verts}
    pi2 = {v: v % n for v in verts}
    t0 = time.perf_counter()
    parts, st = optimized_covering(Lf, pi1, pi2, K, M=M, r=r, N=N, t=t, seed=seed, restarts=restarts,
                                   patience=patience, time_limit=time_limit, verbose=verbose)
    dt = time.perf_counter() - t0
    verify_system(parts, Lf, pi1, pi2, K)
    print(f"[{name}] |F_L|={len(Lf)}  parts={len(parts)}  =>  SC_strict <= {len(parts) - 1}   "
          f"time={dt:.2f}s  chain lengths={[len(p.chain) - 1 for p in parts]}")
    print(f"   LocalSearch calls={st.ls_calls}, adds: free={st.free_adds} dp={st.dp_adds} "
          f"warm={st.warm_adds} cold={st.cold_adds}, failures={st.failures}")
    return parts, dt


